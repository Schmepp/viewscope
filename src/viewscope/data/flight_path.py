"""
The order the viewpoints of a route get flown in, and the way round.

A route says which viewpoints are worth flying; it says nothing about the
order. Flown in plan order a route doubles back on itself over and over,
because the plan is generated by sweeping the model rather than by walking
it, so the line drawn through it is both ugly and far longer than it needs
to be. What is wanted is the shortest path visiting every viewpoint once,
which is the travelling salesman problem: exactly solvable only for routes
far smaller than these, so this settles for a good path found quickly.

Two steps, the standard pair:

    nearest neighbour  builds a path by always flying to the closest
                       viewpoint not yet visited. Quick, and about a quarter
                       longer than the best path, because the last few hops
                       are whatever is left over.
    2-opt              then takes any two hops that cross and uncrosses them,
                       over and over until no pair is left worth swapping.
                       This is what takes the crossings out.

An open path, not a loop: a survey is flown from one end to the other. The
loop is what 2-opt is written for, so an imaginary stop that is no distance
from anywhere joins the two ends, and it is cut out again at the end.

The shortest hop between two viewpoints is very often straight through the
building they are both looking at - on a real plan about a quarter of them
are - so a path that only ordered the viewpoints would fly through the
model. Given an `Obstacle` this plans in two layers instead: hops that hit
the building are struck out, the remaining ones are searched for the
shortest way round from every viewpoint to every other, and the tour is
built on *those* distances. Each hop is then written out as the viewpoints
it actually goes by, so every segment of the line that comes back is one
that was checked and found clear.

Pure numpy, scipy and trimesh. No Qt, no VTK and no scene, so all of it can
be exercised headless.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from scipy import ndimage
from scipy.sparse.csgraph import shortest_path

#: How many voxels the model's diagonal is cut into. The cell this gives is
#: also the clearance the path keeps, because the occupied cells are grown by
#: one before anything is tested against them: the line is kept off the
#: building rather than merely out of it.
VOXELS_ACROSS = 64

#: How far apart points are taken along a hop, as a fraction of a cell. The
#: spacing is absolute - so many metres from the start of the hop, whatever
#: the hop is - so that a hop is judged the same every time it is asked
#: about, rather than by where the samples happened to land. Half a cell is
#: enough: to reach the model a hop has to cross the shell of grown cells
#: around it, which is a cell thick on either side, so four points fall
#: inside it before anything real is touched. Finer only changes the verdict
#: on hops that grazed the clearance and never reached the model, and costs
#: twice the time on every route change to do it.
SAMPLE_FRACTION = 0.5

#: Hops tested at a time. Only there to bound the working array.
PAIR_CHUNK = 2000

#: Past this many viewpoints the distance matrix is the problem rather than
#: the search - it grows as the square - so the path is left as nearest
#: neighbour built it. No plan the viewer loads comes close.
MATRIX_LIMIT = 2000

#: Passes of 2-opt to allow. It converges long before this on a real route;
#: the cap is only here so a pathological one cannot hang the window.
MAX_PASSES = 40

#: An improvement smaller than this is floating point noise, not a shorter
#: path, and taking it would let the loop run for ever.
EPSILON = 1e-9

#: Passes of string pulling. Each one is a shortcut sweep up the stretch and
#: another back down it; two or three is usually all that changes anything.
PULL_PASSES = 4

#: The most points a stretch is cut into before it is pulled. A taut line is
#: read off the corners it bends at, so there have to be enough points on the
#: stretch to find them, but the search grows with the square of them.
PULL_LIMIT = 240


@dataclass(frozen=True)
class FlightPath:
    """A route in the order it gets flown, and the line that flies it."""

    #: The viewpoints, as rows of the positions handed in, in flying order.
    order: tuple[int, ...]
    #: The line itself, (m, 3). The viewpoints, plus any gone by on the way
    #: round the building, so every segment of it is one that was checked.
    points: np.ndarray
    #: How far that line runs, in the units the positions are in.
    length: float
    #: Hops that had to go round the building rather than straight across,
    #: by way of other viewpoints.
    detours: int
    #: Hops that had to climb over it, because nothing on the ground did.
    climbs: int
    #: Hops left going through it, because no way round or over was found.
    crossings: int
    #: Whether the path was planned against a building at all. False means
    #: nothing was checked, not that nothing was in the way.
    checked: bool

    @property
    def clear(self) -> bool:
        """True when the path was checked and no part of it goes through."""
        return self.checked and self.crossings == 0

    @property
    def avoidances(self) -> int:
        """Hops that had to be flown some way other than straight."""
        return self.detours + self.climbs


class Obstacle:
    """What the flight path has to stay out of, as occupied space.

    The mesh as a grid of cells, each either inside the building or not,
    grown by one cell so that a path only just missing the surface is treated
    as hitting it. Testing a hop is then a lookup rather than a ray cast,
    which is what makes it quick enough to do for every pair of viewpoints in
    a route: on a real plan that is some seventeen thousand of them.
    """

    def __init__(self, filled: np.ndarray, origin, pitch: float):
        self._filled = np.asarray(filled, dtype=bool)
        self._origin = np.asarray(origin, dtype=np.float64).reshape(3)
        self._pitch = float(pitch)
        self._high = np.asarray(self._filled.shape, dtype=np.int64) - 1

    @classmethod
    def from_mesh(cls, mesh) -> Obstacle:
        """Build from a trimesh mesh, at a cell sized to the model."""
        bounds = np.asarray(mesh.bounds, dtype=np.float64)
        pitch = float(np.linalg.norm(bounds[1] - bounds[0])) / VOXELS_ACROSS

        voxels = mesh.voxelized(pitch=pitch)
        # Grown by one cell: the clearance the path is asked to keep.
        filled = ndimage.binary_dilation(np.asarray(voxels.matrix, dtype=bool))

        return cls(filled, np.asarray(voxels.bounds, dtype=np.float64)[0], pitch)

    @property
    def clearance(self) -> float:
        """How far the path is kept off the building, near enough."""
        return self._pitch

    @property
    def ceiling(self) -> float:
        """A height with nothing above it, whatever the model looks like."""
        return float(self._origin[2] + self._filled.shape[2] * self._pitch) + self._pitch

    def over_the_top(self, start, end) -> list | None:
        """Two waypoints joining these by way of the sky, or None.

        The last resort, and what a pilot would do: climb, cross above the
        building, descend. Nothing is above the model by definition, so the
        crossing leg is always clear; the two climbs are not - an overhang
        could be in the way - so all three legs are checked before this is
        offered. None when any of them is fouled.
        """
        start = np.asarray(start, dtype=np.float64).reshape(3)
        end = np.asarray(end, dtype=np.float64).reshape(3)

        height = max(self.ceiling, float(start[2]), float(end[2]))
        climb = np.array([start[0], start[1], height])
        descend = np.array([end[0], end[1], height])

        legs = np.array([start, climb, descend])
        nexts = np.array([climb, descend, end])
        if self.blocks(legs, nexts).any():
            return None

        return [climb, descend]

    def blocks(self, starts, ends) -> np.ndarray:
        """Which of these hops pass through the building, as a bool per hop.

        Both arrays are (n, 3) and are read pairwise. Points are taken along
        each hop half a cell apart and looked up in the grid, so a hop is
        blocked the moment any part of it is inside.

        The last cell at either end is not looked at. A viewpoint is where
        the drone has to be, and a survey puts them close in: grown by one
        cell the building swallows the odd viewpoint whole, and reading that
        as a wall would strike out every hop it has and strand it. What is
        asked here is whether the building is in the way between two
        viewpoints, not whether they are near it - they are meant to be.
        """
        starts = np.asarray(starts, dtype=np.float64).reshape(-1, 3)
        ends = np.asarray(ends, dtype=np.float64).reshape(-1, 3)
        blocked = np.zeros(len(starts), dtype=bool)
        if not len(starts):
            return blocked

        spans = np.linalg.norm(ends - starts, axis=1)
        longest = float(spans.max(initial=0.0))
        spacing = self._pitch * SAMPLE_FRACTION
        steps = max(int(np.ceil(longest / spacing)) + 1, 2)
        # Measured from the start of each hop in metres, not in fractions of
        # it, so where the samples fall depends on the hop alone. Batched
        # with a longer hop, a fraction of the way along would move.
        offsets = np.arange(steps, dtype=np.float64) * spacing

        for low in range(0, len(starts), PAIR_CHUNK):
            high = min(low + PAIR_CHUNK, len(starts))
            legs = ends[low:high] - starts[low:high]
            reach = spans[low:high, None]
            # Anything past the end of a hop sits on its end, where it has no
            # say anyway.
            along = np.minimum(offsets[None, :] / np.maximum(reach, EPSILON), 1.0)
            points = starts[low:high, None, :] + along[:, :, None] * legs[:, None, :]

            cells = np.floor((points - self._origin) / self._pitch).astype(np.int64)
            # The grid covers the model and nothing else, so a point beyond
            # it is in open air. It has to be struck out by hand: clipping it
            # to the edge would read it as whatever is on that face of the
            # model, and a viewpoint above the roof would be inside it.
            within = np.all((cells >= 0) & (cells <= self._high), axis=-1)
            np.clip(cells, 0, self._high, out=cells)
            inside = self._filled[cells[..., 0], cells[..., 1], cells[..., 2]] & within

            # Only the stretch clear of both ends has a say. A hop shorter
            # than the two end zones together has none at all, which is
            # right: there is no room between them to fly through.
            between = (along * reach >= self._pitch) & ((1.0 - along) * reach >= self._pitch)

            blocked[low:high] = (inside & between).any(axis=1)

        return blocked

    def blocked_pairs(self, positions) -> np.ndarray:
        """Which viewpoints cannot see each other past the building, (n, n)."""
        points = np.asarray(positions, dtype=np.float64).reshape(-1, 3)
        count = len(points)
        blocked = np.zeros((count, count), dtype=bool)
        if count < 2:
            return blocked

        left, right = np.triu_indices(count, k=1)
        hit = self.blocks(points[left], points[right])

        blocked[left, right] = hit
        blocked[right, left] = hit

        return blocked


def plan_path(positions, obstacle: Obstacle | None = None) -> FlightPath:
    """Plan the flight through these viewpoints, going round `obstacle`.

    Without an obstacle the hops are straight lines and nothing stops them
    crossing the model; that is the right call only when there is no model to
    cross, so the viewer always passes one.
    """
    points = np.asarray(positions, dtype=np.float64).reshape(-1, 3)
    count = len(points)
    if count < 2:
        return FlightPath(
            tuple(range(count)), points.copy(), 0.0, 0, 0, 0, checked=obstacle is not None
        )

    straight = _distances(points)
    if obstacle is None:
        order = _order(points, straight)

        return _assemble(points, order, None, None)

    blocked = obstacle.blocked_pairs(points)
    # What it costs to get from each viewpoint to each other keeping clear,
    # and which way round that goes.
    detoured, previous = _detours(straight, blocked)
    order = _order(points, _payable(detoured, straight))

    return _assemble(points, order, (previous, blocked), obstacle)


def path_length(positions, order=None) -> float:
    """How far a line through these points runs, in their own units."""
    points = np.asarray(positions, dtype=np.float64).reshape(-1, 3)
    if order is not None:
        points = points[list(order)]

    if len(points) < 2:
        return 0.0

    return float(np.linalg.norm(np.diff(points, axis=0), axis=1).sum())


# -- ordering --------------------------------------------------------------


def _order(points: np.ndarray, distances: np.ndarray) -> np.ndarray:
    """The viewpoints in flying order, by whatever distances are handed in."""
    if len(points) < 3:
        return np.arange(len(points))

    order = _nearest_neighbour(points, distances)
    if len(points) <= MATRIX_LIMIT:
        order = _two_opt(order, distances)

    return order


def _distances(points: np.ndarray) -> np.ndarray:
    """Every viewpoint's straight line distance to every other, (n, n)."""
    return np.linalg.norm(points[:, None, :] - points[None, :, :], axis=2)


def _nearest_neighbour(points: np.ndarray, distances: np.ndarray) -> np.ndarray:
    """Build a path by always going to the nearest viewpoint not yet flown."""
    count = len(points)
    unvisited = np.ones(count, dtype=bool)
    order = np.empty(count, dtype=np.int64)

    # The lowest corner of the route is a sensible place to start: an end of
    # the path rather than somewhere in the middle of it.
    current = int(np.lexsort((points[:, 2], points[:, 1], points[:, 0]))[0])
    order[0] = current
    unvisited[current] = False

    for step in range(1, count):
        gaps = np.where(unvisited, distances[current], np.inf)
        current = int(np.argmin(gaps))
        order[step] = current
        unvisited[current] = False

    return order


def _two_opt(order: np.ndarray, distances: np.ndarray) -> np.ndarray:
    """Uncross the path, by reversing any stretch of it that shortens it.

    Works on a loop, which is what 2-opt is written for: row `n` of the
    padded distances is an imaginary stop no distance from any viewpoint, so
    the two ends of the path are joined at no cost and the loop is cut back
    open at the end. Every candidate for one end of a swap is tried at once,
    which is what makes this quick enough to run on every click.
    """
    count = len(order)
    # The imaginary stop, free to reach and free to leave.
    padded = np.zeros((count + 1, count + 1), dtype=np.float64)
    padded[:count, :count] = distances

    tour = np.concatenate([[count], order])
    size = len(tour)

    for _ in range(MAX_PASSES):
        improved = False

        for i in range(1, size - 1):
            before, first = tour[i - 1], tour[i]
            # Each j from i + 1 on: the hop into the stretch is re-made from
            # `before`, and the hop out of it lands on whatever followed j.
            last = tour[i + 1 :]
            after = np.concatenate([tour[i + 2 :], tour[:1]])

            delta = (
                padded[before, last]
                + padded[first, after]
                - padded[before, first]
                - padded[last, after]
            )

            best = int(np.argmin(delta))
            if delta[best] < -EPSILON:
                j = i + 1 + best
                tour[i : j + 1] = tour[i : j + 1][::-1]
                improved = True

        if not improved:
            break

    # Cut the imaginary stop back out, leaving the path open where it was.
    cut = int(np.flatnonzero(tour == count)[0])

    return np.roll(tour, -cut)[1:]


# -- going round -----------------------------------------------------------


def _detours(straight: np.ndarray, blocked: np.ndarray):
    """The shortest clear way from every viewpoint to every other.

    Struck-out hops leave a graph of the ones that are clear; the shortest
    route through that graph is the real cost of getting from one viewpoint
    to another, whether that is straight across or the long way round. Comes
    back with the predecessors too, which is how the way round is read off.
    """
    clear = np.where(blocked, np.inf, straight)
    np.fill_diagonal(clear, 0.0)

    return shortest_path(clear, method="D", directed=False, return_predecessors=True)


def _payable(detoured: np.ndarray, straight: np.ndarray) -> np.ndarray:
    """Detour costs, with a price put on the pairs nothing clear reaches.

    A route in two pieces with the building between them has to be crossed
    somewhere. Rather than let the search fail, crossing is made to cost more
    than any way round ever could, so it is used once and where it is
    cheapest instead of wherever the ordering happened to land.
    """
    unreachable = ~np.isfinite(detoured)
    if not unreachable.any():
        return detoured

    reachable = detoured[np.isfinite(detoured)]
    toll = float(reachable.max(initial=0.0)) * len(detoured) + float(straight.max()) + 1.0

    return np.where(unreachable, toll + straight, detoured)


def _assemble(points: np.ndarray, order: np.ndarray, routing, obstacle) -> FlightPath:
    """Write the order out as the line that actually gets flown.

    Every hop is taken one of three ways, in the order they are worth having:
    straight, when the way is clear; round by other viewpoints, when the
    graph offers a chain; and over the top, when it does not. Only a hop that
    fails all three is flown through the building, and it is counted.
    """
    rows = [int(row) for row in order]
    if routing is None:
        flown = points[rows]

        return FlightPath(tuple(rows), flown, path_length(flown), 0, 0, 0, checked=False)

    previous, blocked = routing

    line: list[np.ndarray] = [points[rows[0]]]
    # Where in the line the viewpoints themselves sit. Everything between two
    # of them is only a way of getting there and may be moved or dropped; the
    # viewpoints may not, because flying them is the point of the route.
    stops: list[int] = [0]
    detours = climbs = crossings = 0

    for start, end in zip(rows, rows[1:], strict=False):
        if not blocked[start, end]:
            line.append(points[end])
        elif (way := _between(previous, start, end)) is not None:
            detours += 1
            line.extend(points[step] for step in way)
        elif (
            over := (
                None if obstacle is None else obstacle.over_the_top(points[start], points[end])
            )
        ) is not None:
            climbs += 1
            line.extend(over)
            line.append(points[end])
        else:
            # Nothing clear joins these two, on the ground or over the top.
            # The hop is flown as it is and the caller is told, rather than
            # silently dropping a viewpoint out of the route.
            crossings += 1
            line.append(points[end])

        stops.append(len(line) - 1)

    flown = _string_pull(line, stops, obstacle)

    return FlightPath(
        tuple(rows), flown, path_length(flown), detours, climbs, crossings, checked=True
    )


# -- pulling the line taut -------------------------------------------------


def _string_pull(line: list[np.ndarray], stops: list[int], obstacle) -> np.ndarray:
    """Take the slack out of the way round, leaving the viewpoints where they are.

    A way round the building comes out of the search as the corners it was
    found by - other viewpoints, or the top of a climb - and those corners are
    wherever the search happened to put them, not where a pilot would turn. A
    hop over a wall leaves at the vertical and crosses at the height of the
    tallest thing on the model, which is why it is drawn as a box.

    So the line is pulled taut, the way a string laid round a corner pulls
    taut when both ends are drawn: any point that can be cut out, because the
    way from the one before it to the one after is clear, is cut out. Every
    segment left has been checked, so a pulled line is no less clear than the
    one it came from, and by the triangle inequality it is never longer.

    Only the stretches between viewpoints are pulled, and only within
    themselves. Pulling across a viewpoint would shorten the line by not
    flying to it, which is not a saving.
    """
    if obstacle is None or len(line) <= len(stops):
        # Every point is a viewpoint: the whole route was flown straight and
        # there is no slack anywhere to take out.
        return np.asarray(line, dtype=np.float64).reshape(-1, 3)

    pulled: list[np.ndarray] = [line[0]]
    for first, last in zip(stops, stops[1:], strict=False):
        stretch = np.asarray(line[first : last + 1], dtype=np.float64)
        pulled.extend(_taut(stretch, obstacle)[1:])

    return np.asarray(pulled, dtype=np.float64).reshape(-1, 3)


def _taut(stretch: np.ndarray, obstacle) -> np.ndarray:
    """One stretch, pulled as tight as the building lets it go.

    Every sweep is checked over before it is kept. A shortcut is taken on the
    strength of one test of one segment, and the sweep then takes the next
    point along on trust; that trust is nearly always well placed, but the
    promise this whole module makes is worth more than the last few metres,
    so a sweep that leaves anything fouling the building is thrown away and
    the stretch is left as the way round it already was. The way round it
    already was is known to be clear: it is made of hops that were tested
    before the line was ever drawn through them.
    """
    if len(stretch) < 3:
        return stretch

    best = stretch
    shortest = path_length(stretch)

    for _ in range(PULL_PASSES):
        # Cut into steps first, and again after every sweep. A taut line
        # bends where the building makes it bend, and it can only be found to
        # bend at a point that is on the line: given only the corners it
        # already has there is nothing between them to pull it onto, and the
        # box stays a box.
        pulled = _resample(best, obstacle.clearance)

        # Up the stretch and back down it: a shortcut the one way is not
        # always a shortcut the other, and the ends tighten last.
        pulled = _shortcut(pulled, obstacle)
        pulled = _shortcut(pulled[::-1], obstacle)[::-1]

        length = path_length(pulled)
        if length > shortest - EPSILON or _fouls(pulled, obstacle):
            break

        best, shortest = pulled, length

    return best


def _fouls(line: np.ndarray, obstacle) -> bool:
    """Whether any segment of a drawn line passes through the building."""
    if len(line) < 2:
        return False

    return bool(obstacle.blocks(line[:-1], line[1:]).any())


def _resample(stretch: np.ndarray, spacing: float) -> np.ndarray:
    """The same line, walked in short steps, keeping every corner it turns at.

    The corners are kept rather than walked past. A point put down between
    two of them cuts the corner off, and a corner of a way round the building
    is exactly where the line is hugging it, so the cut would go through.
    Keeping them means every pair of neighbours lies on one straight piece of
    the line that was already checked, which is what lets the shortcut sweep
    take the next point along on trust.
    """
    kept = np.concatenate([[True], np.any(np.diff(stretch, axis=0) != 0.0, axis=1)])
    deduped = stretch[kept]
    if len(deduped) < 2:
        # Every point of the stretch is the same point. There is nothing to
        # walk, but both ends are handed back so the viewpoint at the far end
        # of it is not dropped out of the route.
        return stretch[[0, -1]]

    legs = np.linalg.norm(np.diff(deduped, axis=0), axis=1)
    total = float(legs.sum())
    if total <= 0.0:
        return deduped[[0, -1]]

    # Share the points out over the whole stretch, so a long way round is cut
    # no finer than a short one and the search stays bounded either way.
    room = max(PULL_LIMIT - len(deduped), 1)
    spacing = max(spacing, total / room, EPSILON)

    walked = [deduped[0]]
    for leg, (here, there) in zip(legs, zip(deduped, deduped[1:], strict=False), strict=False):
        pieces = max(int(np.ceil(leg / spacing)), 1)
        steps = np.arange(1, pieces + 1, dtype=np.float64)[:, None] / pieces
        walked.extend(here + steps * (there - here))

    return np.asarray(walked, dtype=np.float64).reshape(-1, 3)


def _shortcut(stretch: np.ndarray, obstacle) -> np.ndarray:
    """One sweep: from each point kept, jump to the furthest one still clear."""
    last = len(stretch) - 1
    kept = [0]
    at = 0

    while at < last:
        # The next point along is always reachable - it is a piece of the
        # line that was already checked - so it is the floor, not a candidate.
        ahead = np.arange(at + 2, last + 1)
        reach = at + 1

        if len(ahead):
            here = np.repeat(stretch[at][None, :], len(ahead), axis=0)
            clear = ~obstacle.blocks(here, stretch[ahead])
            if clear.any():
                reach = int(ahead[clear].max())

        kept.append(reach)
        at = reach

    return stretch[kept]


def _between(previous: np.ndarray, start: int, end: int) -> list[int] | None:
    """The viewpoints gone by from `start` to `end`, `start` itself left off.

    None when the two are not joined by clear hops at all.
    """
    way: list[int] = []
    at = end

    while at != start:
        way.append(at)
        at = int(previous[start, at])
        if at < 0:
            return None

    way.reverse()

    return way
